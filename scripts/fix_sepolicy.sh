#!/usr/bin/env bash
# Make a vendor's sepolicy compile together with the port's system/system_ext/product policy,
# exactly like init does on boot (secilc -N, no neverallow checks). Runs inside the VM.
# Fixes, in a loop:
#   - versioned attribute (X_30_0) referenced by a port mapping but never declared -> declare it (empty)
#   - genfscon defined by both system_ext and vendor -> drop the vendor line (port's label wins)
# Usage: fix_sepolicy.sh <vendor tree> <system mount> <system_ext mount> <product mount> <log file>
set -uo pipefail
VT=$1; SYS=$2; SE=$3; PR=$4; LOG=$5
export LC_ALL=C
VC=$VT/etc/selinux/vendor_sepolicy.cil
VER=$(cat "$VT/etc/selinux/plat_sepolicy_vers.txt")
S=$SYS/system/etc/selinux
FILES="$S/plat_sepolicy.cil $S/mapping/$VER.cil"
[ -f "$S/mapping/$VER.compat.cil" ] && FILES="$FILES $S/mapping/$VER.compat.cil"
for p in "$SE" "$PR"; do
  for c in "$p"/etc/selinux/*_sepolicy.cil "$p/etc/selinux/mapping/$VER.cil"; do [ -f "$c" ] && FILES="$FILES $c"; done
done
FILES="$FILES $VT/etc/selinux/plat_pub_versioned.cil $VC"
echo ";; oneui-renoir: sepolicy fixes for the port (generated by fix_sepolicy.sh)" >> "$VC"
: > "$LOG"
TD=$(mktemp -d); trap 'rm -rf "$TD"' EXIT
# Samsung's system_ext/product mappings reference hundreds of versioned attributes (X_30_0) that only a
# Samsung vendor declares. Declare every referenced-but-undeclared one up front instead of one per secilc run.
SUF=_${VER/./_}
# shellcheck disable=SC2086
grep -ohE "[A-Za-z0-9_.-]+$SUF\b" $FILES | sort -u > "$TD/used"
# shellcheck disable=SC2086
grep -ohE "^\(typeattribute [A-Za-z0-9_.-]+$SUF\)" $FILES | sed 's/^(typeattribute //; s/)$//' | sort -u > "$TD/declared"
comm -23 "$TD/used" "$TD/declared" > "$TD/missing"
while read -r name; do echo "(typeattribute $name)" >> "$VC"; echo "declare: $name" >> "$LOG"; done < "$TD/missing"
echo "pre-declared $(grep -c . "$TD/missing") versioned attributes"
for i in $(seq 1 500); do
  # shellcheck disable=SC2086
  if secilc -v -m -M true -G -N -c 30 -o "$TD/policy.bin" -f /dev/null $FILES > "$TD/secilc.err" 2>&1; then
    echo "policy OK ($(grep -c . "$LOG") fixes)"; exit 0
  fi
  if grep -q 'conflicting genfscon' "$TD/secilc.err"; then
    ln=$(grep -A2 'conflicting genfscon' "$TD/secilc.err" | grep -oE "at $VC:[0-9]+" | head -1 | sed 's/.*://')
    [ -n "$ln" ] || { cat "$TD/secilc.err"; exit 1; }
    echo "drop genfscon: $(sed -n "${ln}p" "$VC")" >> "$LOG"
    # rewrite in place: sed -i would create a new file without the selinux xattr
    sed "${ln}s/^/;; dropped (system_ext wins): /" "$VC" > "$TD/vc"; cat "$TD/vc" > "$VC"
    continue
  fi
  loc=$(grep -oE 'at [^ ]+:[0-9]+' "$TD/secilc.err" | head -1 | sed 's/^at //')
  f=${loc%:*}; l=${loc##*:}
  name=$( [ -f "$f" ] && sed -n "${l}p" "$f" | grep -oE "[A-Za-z0-9_.-]+_${VER/./_}\b" | head -1 )
  if [ -n "$name" ] && ! grep -q "^(typeattribute $name)$" "$VC"; then
    echo "(typeattribute $name)" >> "$VC"; echo "declare: $name" >> "$LOG"; continue
  fi
  echo "unhandled sepolicy error:"; tail -5 "$TD/secilc.err"; exit 1
done
echo "too many iterations"; exit 1
