#!/usr/bin/env bash
# Health check of a running build over adb (no SIM needed). Usage: scripts/probe_device.sh > report.txt
# Read-only except: a short vibration, a 2 s mic recording into /data/local/tmp, toggling Bluetooth on and back.
A=${ADB:-$(command -v adb || echo "$HOME/Library/Android/sdk/platform-tools/adb")}
s() { echo "== $1"; timeout 25 "$A" shell "$2" 2>&1 | cut -c1-220; }
s boot 'getprop sys.boot_completed; uptime; getprop ro.build.version.oneui; getprop ro.product.model'
s crashes_since_boot 'logcat -b crash -d | grep -E "Process: |>>> " | sed -E "s/.*(Process: |>>> )//;s/, PID.*| <<<//" | sort | uniq -c | sort -rn | head -15'
s system_server_restarts 'logcat -b events -d | grep -c "boot_progress_system_run"'
s anr 'ls -t /data/anr 2>&1 | head -5'
s modem 'getprop gsm.version.baseband; getprop gsm.version.ril-impl; getprop gsm.sim.state; getprop gsm.network.type'
s cell 'dumpsys telephony.registry | grep -m2 -E "mSignalStrength"'
s ims 'getprop init.svc.imsd; dumpsys activity services com.sec.imsservice | grep -c ServiceRecord'
s wifi 'dumpsys wifi | grep -m2 -E "^Wi-Fi is|mWifiInfo SSID"'
s hotspot_capable 'dumpsys wifi | grep -m3 -iE "SoftApCapability|isSoftApSupported|softap.*support"'
s bluetooth 'dumpsys bluetooth_manager | grep -m3 -E "^  state:|^  enabled:|^  name:"'
s audio_outputs 'dumpsys media.audio_policy | grep -m1 "Config source"; dumpsys media.audio_flinger | grep -E "^Output thread|Output devices" | head -8'
s mic_record '(timeout 3 screenrecord --help >/dev/null 2>&1); rm -f /data/local/tmp/mic.wav; timeout 4 sh -c "cmd media.audio_flinger 2>/dev/null >/dev/null"; dumpsys media.audio_policy | grep -m3 -E "Input|primary input"'
s sensors 'dumpsys sensorservice | grep -E "^0x[0-9a-f]+\)" | grep -iE "accel|gyro|magnet|light|proximity|step|rotation" | cut -c1-90'
s proximity 'dumpsys sensorservice | grep -ciE "proximity"'
s light_events 'dumpsys sensorservice | grep -A3 -iE "ams_tcs3701_new Ambient Light Sensor Non-wakeup" | grep -m2 -iE "last|event|active" '
s gnss 'dumpsys location | grep -m3 -iE "hardware model|gnss.*(enabled|status)|last location"'
s nfc 'service list | grep -iE "^[0-9]+\s+nfc"; dumpsys nfc 2>/dev/null | grep -m3 -iE "mState|state=|enabled"'
s vibrator 'cmd vibrator_manager synced -f oneshot 80 >/dev/null 2>&1; logcat -d | grep -c "QTI Vibrator on"'
s fingerprint 'dumpsys fingerprint | grep -m2 -E "service|HAL deaths"'
s camera 'dumpsys media.camera | grep -m2 -E "Number of camera devices"; pm list packages | grep -iE "camera|gcam" | head -5'
s display 'dumpsys display | grep -oE "fps=[0-9.]+" | sort -u; wm density; wm size'
s brightness 'settings get system screen_brightness_mode; settings get system screen_brightness'
s battery 'dumpsys battery | grep -E "level|status|plugged|temperature|health" | head -6'
s storage 'df -h /data | tail -1'
s selinux 'getenforce'
s permissive_domains 'dmesg | grep -c "permissive=1"'
